#!/usr/bin/env python3
"""Rebuild index.html from the meta tags in public/recipes/*.html.

Usage (from the cooking repo root): python3 .claude/skills/recipe/build_index.py

Each recipe page must carry <meta name="recipe-course"> with one of the
COURSES keys below. The script stops with an error if a page has no course
or an unknown course. Do not edit index.html by hand. Run this script.
"""
import glob
import html
import re
import sys

COURSES = {
    "mains": "Mains",
    "sides": "Sides and Salads",
    "sauces": "Sauces and Condiments",
    "breakfast": "Breakfast",
    "baking": "Baking and Sweets",
    "bases": "Doughs and Bases",
}
RECENT = 5
SPEEDS = ("weeknight", "weekend")


def meta(src, name):
    m = re.search(rf'<meta name="recipe-{name}" content="([^"]*)">', src)
    return m.group(1).strip() if m else ""


recipes, errors = [], []
for path in sorted(glob.glob("public/recipes/*.html")):
    src = open(path, encoding="utf-8").read()
    fn = path.split("/")[-1]
    course = meta(src, "course")
    if course not in COURSES:
        errors.append(f"{fn}: recipe-course is '{course}', expected one of {list(COURSES)}")
        continue
    types = [t.strip() for t in meta(src, "type").split(",")]
    cuisine = meta(src, "cuisine")
    recipes.append(dict(
        fn=fn,
        date=fn[:10],
        name=re.search(r"<title>(.*?)</title>", src, re.S).group(1).strip(),
        course=course,
        speed=next((t for t in types if t in SPEEDS), ""),
        cuisine="" if cuisine in ("", "other") else cuisine,
        search=" ".join(dict.fromkeys(
            w for w in re.split(r"[,\s]+", " ".join([meta(src, "tags"), meta(src, "main-ingredient"), COURSES[course]]).lower())
            if w and w not in ("other", "and"))),
    ))
if errors:
    sys.exit("\n".join(errors))


def item(r, show_date=False):
    tags = [t for t in (r["speed"], r["cuisine"]) if t]
    if show_date:
        tags.append(r["date"])
    meta_span = f'<span class="meta">{" · ".join(tags)}</span>' if tags else ""
    search = html.escape(f'{html.unescape(r["name"]).lower()} {r["search"]}', quote=True)
    return (f'    <li data-speed="{r["speed"]}" data-search="{search}">'
            f'<a href="public/recipes/{r["fn"]}">{r["name"]}</a>{meta_span}</li>')


newest = sorted(recipes, key=lambda r: (r["date"], r["fn"]), reverse=True)[:RECENT]
sections = [
    '  <section id="recent">\n  <h2>Recent</h2>\n  <ul>\n'
    + "\n".join(item(r, show_date=True) for r in newest) + "\n  </ul>\n  </section>"
]
for key, title in COURSES.items():
    rows = sorted((r for r in recipes if r["course"] == key), key=lambda r: html.unescape(r["name"]).lower())
    if rows:
        sections.append(f'  <section class="course" id="{key}">\n  <h2>{title}</h2>\n  <ul>\n'
                        + "\n".join(item(r) for r in rows) + "\n  </ul>\n  </section>")

PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Cooking</title>
  <!-- Generated by .claude/skills/recipe/build_index.py. Do not edit by hand. -->
  <style>
    /* Palette from kevinrocci.com/work (yellow-billed magpie).
       c50–c950: one tinted scale on the hue of the wing blue (#1A5F92),
       near-white to near-black. Every neutral comes from it. */
    :root {
      --c50: #F5FAFE; --c100: #EDF2F7; --c200: #DDE4EA; --c300: #C6CFD7;
      --c400: #9FABB6; --c500: #768593; --c600: #576878; --c700: #404F5C;
      --c800: #2B3741; --c900: #192229; --c950: #0E151B;
      --accent: #1A5F92;  /* wing blue: links */
      --spark: #F0AD1B;   /* eye ring: one mark on the title rule */
    }
    body { font-family: Georgia, serif; max-width: 680px; margin: 40px auto; padding: 0 20px; color: var(--c900); background: var(--c50); line-height: 1.7; }
    h1 { font-size: 1.8rem; padding-bottom: 8px; background: linear-gradient(to right, var(--spark) 0 3rem, var(--c900) 3rem) left bottom / 100% 2px no-repeat; }
    h2 { font-size: 1.1rem; margin-top: 2rem; color: var(--c700); text-transform: uppercase; letter-spacing: 0.05em; }
    ul { list-style: none; padding: 0; }
    ul li { margin-bottom: 0.4rem; }
    ul li a { color: var(--c900); text-decoration: none; }
    ul li a:hover { color: var(--accent); text-decoration: underline; }
    .meta { font-size: 0.8rem; color: var(--c600); margin-left: 0.75rem; white-space: nowrap; }
    .jump { font-size: 0.85rem; color: var(--c600); margin: -0.5rem 0 1rem; }
    .jump a { color: var(--c600); text-decoration: none; margin-right: 0.9rem; white-space: nowrap; display: inline-block; }
    .jump a:hover { color: var(--accent); text-decoration: underline; }
    .filter { display: flex; flex-wrap: wrap; gap: 0.5rem; align-items: center; margin: 1rem 0 0.5rem; }
    .filter[hidden], [hidden] { display: none; }
    .filter input { flex: 1 1 14rem; min-width: 0; font: inherit; font-size: 1rem; padding: 0.4rem 0.6rem; border: 1px solid var(--c300); border-radius: 4px; background: #fff; color: var(--c900); }
    .filter input:focus { outline: 2px solid var(--accent); outline-offset: 1px; border-color: var(--accent); }
    .chips { display: flex; gap: 0.4rem; }
    .filter button { font: inherit; font-size: 0.85rem; padding: 0.35rem 0.75rem; border: 1px solid var(--c300); border-radius: 999px; background: none; color: var(--c700); cursor: pointer; }
    .filter button:hover { border-color: var(--accent); color: var(--accent); }
    .filter button[aria-pressed="true"] { background: var(--accent); border-color: var(--accent); color: #fff; }
    .empty { color: var(--c600); font-style: italic; }
    nav { margin-top: 3rem; font-size: 0.85rem; }
    nav a { color: var(--c600); text-decoration: none; }
    nav a:hover { text-decoration: underline; }
  </style>
</head>
<body>
  <h1>Cooking</h1>
  <p class="jump">{jump}</p>

  <div class="filter" hidden>
    <input type="search" id="q" placeholder="Search: pork, fennel, japanese…" aria-label="Search recipes">
    <div class="chips" role="group" aria-label="Filter by cadence">
      <button type="button" data-speed="weeknight" aria-pressed="false">Weeknight</button>
      <button type="button" data-speed="weekend" aria-pressed="false">Weekend</button>
    </div>
  </div>
  <p class="empty" id="empty" hidden>No recipes match.</p>

{sections}

  <nav><a href="https://kevinrocci.com/">← kevinrocci.com</a></nav>

  <script>
    (function () {
      var box = document.querySelector(".filter"), q = document.getElementById("q");
      var buttons = box.querySelectorAll("button"), speed = "";
      var recent = document.getElementById("recent"), empty = document.getElementById("empty");
      box.hidden = false;
      function apply() {
        var terms = q.value.toLowerCase().trim().split(/\\s+/).filter(Boolean);
        var filtering = terms.length > 0 || speed !== "";
        recent.hidden = filtering;
        var shown = 0;
        document.querySelectorAll("section.course").forEach(function (sec) {
          var n = 0;
          sec.querySelectorAll("li").forEach(function (li) {
            var hay = li.dataset.search;
            var ok = (!speed || li.dataset.speed === speed) &&
                     terms.every(function (t) { return hay.indexOf(t) !== -1; });
            li.hidden = !ok;
            if (ok) n++;
          });
          sec.hidden = n === 0;
          shown += n;
        });
        empty.hidden = shown > 0;
      }
      q.addEventListener("input", apply);
      buttons.forEach(function (b) {
        b.addEventListener("click", function () {
          speed = speed === b.dataset.speed ? "" : b.dataset.speed;
          buttons.forEach(function (x) { x.setAttribute("aria-pressed", String(x.dataset.speed === speed)); });
          apply();
        });
      });
    })();
  </script>
</body>
</html>
"""

present = [k for k in COURSES if any(r["course"] == k for r in recipes)]
jump = "".join(f'<a href="#{k}">{COURSES[k]}</a>' for k in present)
out = PAGE.replace("{jump}", jump).replace("{sections}", "\n\n".join(sections))
open("index.html", "w", encoding="utf-8").write(out)
print(f"index.html: {len(recipes)} recipes, {len(present)} courses")
